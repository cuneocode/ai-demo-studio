"""Build the Chuck Robbins hypothetical advisor sample locally, with no network or model calls.

Run with the wealth virtualenv. Uses the real deterministic screening, suitability,
action sizing and claim verification code. This is a code-written sample, not a
recording of AI inference; it is intentionally not approvable.
"""
from __future__ import annotations

import asyncio
import json
import socket
import sys
from pathlib import Path
from unittest.mock import patch

SERVICE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(SERVICE))
import advisory
import security
from fixtures import fictional_snapshot, fixture_snapshot, household
from runlog import store
from usage import ModelUsage, model_usage


def offline_snapshot(ticker):
    fictional = fictional_snapshot(ticker)
    data = fictional or fixture_snapshot(ticker)
    if data is None:
        raise ValueError(f"No committed snapshot for {ticker}")
    return data, "fictional" if fictional else "fixture"


async def no_model(*_args, **_kwargs):
    return None, "fixture"


async def build():
    usage = ModelUsage()
    token = model_usage.set(usage)
    record = household("chuck-robbins")
    name = "advisory-chuck-robbins"
    try:
        with patch.object(socket.socket, "connect", side_effect=RuntimeError("Sample generation cannot use the network")), \
             patch.object(advisory, "get_snapshot", offline_snapshot), \
             patch.object(advisory, "run_deep_agent", no_model), \
             patch.object(security.defense, "key", ""), patch.object(security.defense, "mode", "off"), \
             patch.object(store, "cache_dir", None):
            run = store.open(label="Chuck Robbins · hypothetical advisor sample · no model", scenario=name)
            with store.bind(run.id):
                result = await advisory.run_meeting_prep(record, research=None, briefing=None, callbacks=[])
                result.update(run_id=run.id, served_by=None, usage=usage.summary(),
                              security={"mode": "off", "status": "disabled", "checks": 0, "blocked": 0, "errors": 0})
                result["brief"]["reason"] = "Saved hypothetical example generated by code; no model or hosted control was called."
                store.finish(run.id, "completed", result)
            path = store.record_golden(run.id, name, title=run.label, synthetic=True)
            doc = json.loads(path.read_text())
            doc["note"] = "Code-written hypothetical advisor sample. Chuck Robbins's public role is sourced from Cisco; financial data and events are invented. No model, AI Defense, or hosted Agent Control call was made. Replay does not consume the current session's handoff."
            doc["public_profile"] = record["public_profile"]
            path.write_text(json.dumps(doc, indent=1) + "\n")
            print(f"Built {path.name}: {len(doc['events'])} events, {usage.llm_calls} model calls, approval {result['approval']['status']}")
    finally:
        model_usage.reset(token)


if __name__ == "__main__":
    asyncio.run(build())
